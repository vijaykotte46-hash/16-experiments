"""Small reproducible evidence runner. Private keys stay in temporary directories."""
import contextlib
import datetime
import io
import json
import platform
import shlex
import subprocess
import sys
from pathlib import Path


def command(args, cwd=None, expected=0, quiet=False):
    args = [str(x) for x in args]
    print('$ ' + shlex.join(args))
    proc = subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=90)
    if not quiet:
        print((proc.stdout + proc.stderr).strip())
    print('Exit code:', proc.returncode)
    if expected == 'nonzero':
        assert proc.returncode != 0, 'Expected this negative test to fail'
    else:
        assert proc.returncode == expected, proc.stderr
    return proc


def record(script, experiment):
    directory = Path(script).resolve().parent
    results = directory / 'results'
    results.mkdir(exist_ok=True)
    captured = io.StringIO()
    with contextlib.redirect_stdout(captured):
        print('ACTUAL EXECUTION LOG — generated by running the supplied program')
        print('UTC:', datetime.datetime.now(datetime.timezone.utc).isoformat())
        print('Platform:', platform.system(), platform.machine())
        print('Python:', platform.python_version())
        print('This is a CLI run; it is not a screenshot of a Windows application.')
        print()
        data = experiment(results)
        print('\nAll assertions passed.')
    (results / 'execution.txt').write_text(captured.getvalue(), encoding='utf-8')
    (results / 'summary.json').write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
    print(captured.getvalue())

